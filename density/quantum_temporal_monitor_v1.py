@dataclass(frozen=True)
class MonitorOp:
    """A programmed observation span; events inside it remain emergent."""

    event_id: str
    start_s: float
    stop_s: float
    channels: tuple[JumpChannel, ...]

    def __post_init__(self) -> None:
        object.__setattr__(self, "event_id", _label(self.event_id, "event_id"))
        start = _finite(self.start_s, "start_s", minimum=0.0)
        stop = _finite(self.stop_s, "stop_s", minimum=0.0)
        if stop <= start:
            raise ValueError("MonitorOp stop_s must be greater than start_s")
        channels = tuple(self.channels)
        if not channels or any(not isinstance(channel, JumpChannel) for channel in channels):
            raise ValueError("MonitorOp requires one or more JumpChannel values")
        dimensions = {channel.operator.shape for channel in channels}
        if len(dimensions) != 1:
            raise ValueError("all monitor channels must use one Hilbert-space dimension")
        if len({channel.name for channel in channels}) != len(channels):
            raise ValueError("monitor channel names must be unique")
        object.__setattr__(self, "start_s", start)
        object.__setattr__(self, "stop_s", stop)
        object.__setattr__(self, "channels", channels)


