"""Continuous quantum monitoring and quantum-derived rhythm, version 1.

This module keeps three operations distinct:

* ``GateOp`` is a scheduled coherent transformation.
* ``MeasureOp`` is a scheduled discrete instrument that produces one outcome.
* ``MonitorOp`` opens a continuous observation interval in which jump times
  are generated by the conditional quantum dynamics.

The circuit and ZX views are lenses on the same immutable operation objects.
They do not own separate copies of musical events.  A monitored jump updates
``rho`` before observables, rhythm projection, and sound-facing excitation are
computed.

The implementation is a simulator.  Its events are not detector observations
and are never relabelled as hardware evidence.
"""

