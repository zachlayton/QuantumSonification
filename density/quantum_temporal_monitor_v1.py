def _label(value: str, name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{name} must be a nonempty string")
    return value.strip()


def _finite(value: float, name: str, *, minimum: float | None = None) -> float:
    result = float(value)
    if not math.isfinite(result):
        raise ValueError(f"{name} must be finite")
    if minimum is not None and result < minimum:
        raise ValueError(f"{name} must be >= {minimum}")
    return result


def _targets(values: Sequence[int]) -> tuple[int, ...]:
    targets = tuple(int(value) for value in values)
    if not targets or any(value < 0 for value in targets):
        raise ValueError("targets must contain nonnegative qubit indices")
    if len(set(targets)) != len(targets):
        raise ValueError("targets must be unique")
    return targets


def _immutable_array(value: object, dtype: np.dtype | type) -> np.ndarray:
    """Copy an array onto a bytes-backed buffer whose write flag cannot reopen."""

    prepared = np.ascontiguousarray(np.asarray(value, dtype=dtype))
    return np.frombuffer(prepared.tobytes(), dtype=prepared.dtype).reshape(prepared.shape)


def _matrix(value: ComplexMatrix, name: str) -> ComplexMatrix:
    matrix = np.asarray(value, dtype=np.complex128)
    if matrix.ndim != 2 or matrix.shape[0] != matrix.shape[1]:
        raise ValueError(f"{name} must be a square matrix")
    if matrix.shape[0] < 1 or not np.all(np.isfinite(matrix)):
        raise ValueError(f"{name} must be a finite nonempty matrix")
    return _immutable_array(matrix, np.complex128)


def _operator_dimension_for_targets(matrix: ComplexMatrix, targets: tuple[int, ...], name: str) -> None:
    expected = 2 ** len(targets)
    if matrix.shape != (expected, expected):
        raise ValueError(f"{name} shape must be {expected}x{expected} for {len(targets)} targets")


def _density(value: ComplexMatrix, name: str = "rho", tolerance: float = 1e-9) -> ComplexMatrix:
    state = _matrix(value, name)
    if not np.allclose(state, state.conj().T, atol=tolerance, rtol=0.0):
        raise ValueError(f"{name} must be Hermitian")
    trace = complex(np.trace(state))
    if abs(trace.imag) > tolerance or trace.real <= 0.0:
        raise ValueError(f"{name} must have positive real trace")
    normalized = np.asarray(state / trace.real, dtype=np.complex128)
    minimum = float(np.linalg.eigvalsh(normalized).min())
    if minimum < -tolerance:
        raise ValueError(f"{name} must be positive semidefinite; minimum eigenvalue={minimum}")
    return _immutable_array(normalized, np.complex128)


@dataclass(frozen=True)
class GateOp:
    event_id: str
    time_s: float
    targets: tuple[int, ...]
    unitary: ComplexMatrix

    def __post_init__(self) -> None:
        object.__setattr__(self, "event_id", _label(self.event_id, "event_id"))
        object.__setattr__(self, "time_s", _finite(self.time_s, "time_s", minimum=0.0))
        targets = _targets(self.targets)
        unitary = _matrix(self.unitary, "unitary")
        _operator_dimension_for_targets(unitary, targets, "unitary")
        identity = np.eye(unitary.shape[0], dtype=np.complex128)
        if not np.allclose(unitary.conj().T @ unitary, identity, atol=1e-10, rtol=0.0):
            raise ValueError("unitary must satisfy U^dagger U = I")
        object.__setattr__(self, "targets", targets)
        object.__setattr__(self, "unitary", unitary)


@dataclass(frozen=True)
class MeasureOp:
    """One scheduled selective/nonselective instrument opportunity.

    The Kraus groups define possible outcomes.  This object does not imply
    that a particular outcome has already been registered.
    """

    event_id: str
    time_s: float
    targets: tuple[int, ...]
    kraus_operators: tuple[ComplexMatrix, ...]

    def __post_init__(self) -> None:
        object.__setattr__(self, "event_id", _label(self.event_id, "event_id"))
        object.__setattr__(self, "time_s", _finite(self.time_s, "time_s", minimum=0.0))
        targets = _targets(self.targets)
        operators = tuple(_matrix(value, "kraus operator") for value in self.kraus_operators)
        if not operators:
            raise ValueError("MeasureOp requires at least one Kraus operator")
        for operator in operators:
            _operator_dimension_for_targets(operator, targets, "kraus operator")
        completeness = sum(
            (operator.conj().T @ operator for operator in operators),
            np.zeros_like(operators[0]),
        )
        if not np.allclose(
            completeness,
            np.eye(operators[0].shape[0]),
            atol=1e-10,
            rtol=0.0,
        ):
            raise ValueError("MeasureOp Kraus operators must be trace preserving")
        object.__setattr__(self, "targets", targets)
        object.__setattr__(self, "kraus_operators", operators)


