@dataclass(frozen=True)
class QuantumEvent:
    """One simulated conditional jump, distinct from a detector record."""

    event_id: str
    time_s: float
    source_id: str
    channel: str
    rate_hz: float
    probability: float
    backaction_norm: float
    rho_before: ComplexMatrix
    rho_after: ComplexMatrix
    origin: Literal["simulated_quantum_trajectory"] = "simulated_quantum_trajectory"
    detector_state_before: int | None = None
    detector_state_after: int | None = None
    record_confidence: float | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "event_id", _label(self.event_id, "event_id"))
        object.__setattr__(self, "source_id", _label(self.source_id, "source_id"))
        object.__setattr__(self, "channel", _label(self.channel, "channel"))
        object.__setattr__(self, "time_s", _finite(self.time_s, "time_s", minimum=0.0))
        object.__setattr__(self, "rate_hz", _finite(self.rate_hz, "rate_hz", minimum=0.0))
        probability = _finite(self.probability, "probability", minimum=0.0)
        if probability > 1.0:
            raise ValueError("probability must lie in [0, 1]")
        object.__setattr__(self, "probability", probability)
        object.__setattr__(
            self,
            "backaction_norm",
            _finite(self.backaction_norm, "backaction_norm", minimum=0.0),
        )
        before = _density(self.rho_before, "rho_before")
        after = _density(self.rho_after, "rho_after")
        if before.shape != after.shape:
            raise ValueError("event density matrices must have matching shapes")
        object.__setattr__(self, "rho_before", before)
        object.__setattr__(self, "rho_after", after)
        if self.origin != "simulated_quantum_trajectory":
            raise ValueError("v1 only emits explicitly simulated trajectory events")
        if (
            self.detector_state_before is not None
            or self.detector_state_after is not None
            or self.record_confidence is not None
        ):
            raise ValueError(
                "simulated trajectory events cannot claim detector states or record confidence"
            )

    def to_record(self, *, include_matrices: bool = True) -> dict[str, object]:
        record: dict[str, object] = {
            "event_id": self.event_id,
            "time_s": self.time_s,
            "source_id": self.source_id,
            "channel": self.channel,
            "rate_hz": self.rate_hz,
            "probability": self.probability,
            "backaction_norm": self.backaction_norm,
            "origin": self.origin,
            "detector_state_before": self.detector_state_before,
            "detector_state_after": self.detector_state_after,
            "record_confidence": self.record_confidence,
        }
        if include_matrices:
            record["rho_before"] = _complex_record(self.rho_before)
            record["rho_after"] = _complex_record(self.rho_after)
        return record


def stabilize_density_matrix(rho: ComplexMatrix, tolerance: float = 1e-9) -> ComplexMatrix:
    """Remove roundoff non-Hermiticity without repairing physical negativity."""

    state = np.asarray(rho, dtype=np.complex128)
    if state.ndim != 2 or state.shape[0] != state.shape[1] or not np.all(np.isfinite(state)):
        raise ValueError("density matrix must be finite and square")
    state = 0.5 * (state + state.conj().T)
    trace = complex(np.trace(state))
    if abs(trace.imag) > tolerance or trace.real <= 0.0:
        raise ValueError("density matrix has nonpositive or complex trace")
    state = state / trace.real
    minimum = float(np.linalg.eigvalsh(state).min())
    if minimum < -tolerance:
        raise ValueError(f"density matrix lost positivity: {minimum}")
    return _immutable_array(state, np.complex128)


class QuantumTrajectoryEngine:
    """First-order Monte Carlo wave-function evolution for density matrices."""

    def __init__(self, seed: int | None = None, maximum_step_probability: float = 0.05):
        self.seed = None if seed is None else int(seed)
        self.rng = np.random.default_rng(self.seed)
        maximum = _finite(maximum_step_probability, "maximum_step_probability", minimum=0.0)
        if maximum <= 0.0 or maximum > 1.0:
            raise ValueError("maximum_step_probability must lie in (0, 1]")
        self.maximum_step_probability = maximum
        self.event_count = 0

    def step(
        self,
        *,
        rho: ComplexMatrix,
        hamiltonian: ComplexMatrix,
        channels: tuple[JumpChannel, ...],
        time_s: float,
        dt_s: float,
        source_id: str,
    ) -> tuple[ComplexMatrix, QuantumEvent | None]:
        state = _density(rho)
        hamiltonian_matrix = _matrix(hamiltonian, "hamiltonian")
        if hamiltonian_matrix.shape != state.shape:
            raise ValueError("hamiltonian and rho dimensions must match")
        if not np.allclose(
            hamiltonian_matrix,
            hamiltonian_matrix.conj().T,
            atol=1e-10,
            rtol=0.0,
        ):
            raise ValueError("hamiltonian must be Hermitian")
        declared_channels = tuple(channels)
        if not declared_channels or any(not isinstance(channel, JumpChannel) for channel in declared_channels):
            raise ValueError("step requires one or more JumpChannel values")
        if any(channel.operator.shape != state.shape for channel in declared_channels):
            raise ValueError("jump channel and rho dimensions must match")
        time = _finite(time_s, "time_s", minimum=0.0)
        dt = _finite(dt_s, "dt_s", minimum=0.0)
        if dt <= 0.0:
            raise ValueError("dt_s must be positive")
        source = _label(source_id, "source_id")

        rates = np.asarray(
            [
                float(np.trace(channel.operator @ state @ channel.operator.conj().T).real)
                for channel in declared_channels
            ],
            dtype=float,
        )
        if not np.all(np.isfinite(rates)) or float(rates.min()) < -1e-10:
            raise ValueError("jump rates must be finite and nonnegative")
        rates = np.maximum(rates, 0.0)
        probabilities = dt * rates
        total_probability = float(probabilities.sum())
        if total_probability > self.maximum_step_probability:
            raise ValueError(
                "time step is too large for reliable jump simulation: "
                f"total probability {total_probability:.8g} exceeds {self.maximum_step_probability:.8g}"
            )

        if total_probability > 0.0 and float(self.rng.random()) < total_probability:
            weights = probabilities / total_probability
            index = int(self.rng.choice(len(declared_channels), p=weights))
            channel = declared_channels[index]
            numerator = channel.operator @ state @ channel.operator.conj().T
            denominator = complex(np.trace(numerator))
            if denominator.real <= 0.0 or abs(denominator.imag) > 1e-9:
                raise RuntimeError("selected jump has no normalizable posterior")
            state_after = stabilize_density_matrix(numerator / denominator.real)
            self.event_count += 1
            event = QuantumEvent(
                event_id=f"{source}:jump:{self.event_count:06d}",
                time_s=time + dt,
                source_id=source,
                channel=channel.name,
                rate_hz=float(rates[index]),
                probability=float(probabilities[index]),
                backaction_norm=float(np.linalg.norm(state_after - state)),
                rho_before=state,
                rho_after=state_after,
            )
            return state_after, event

        loss = sum(
            (channel.operator.conj().T @ channel.operator for channel in declared_channels),
            np.zeros_like(state),
        )
        effective_hamiltonian = hamiltonian_matrix - 0.5j * loss
        no_jump = np.eye(state.shape[0], dtype=np.complex128) - 1j * effective_hamiltonian * dt
        state_after = no_jump @ state @ no_jump.conj().T
        return stabilize_density_matrix(state_after), None


