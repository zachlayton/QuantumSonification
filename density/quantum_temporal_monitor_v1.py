def _write_pcm16(path: Path, samples: NDArray[np.floating], sample_rate_hz: int, gain: float) -> None:
    scaled = np.clip(np.asarray(samples, dtype=float) * gain, -1.0, 1.0)
    pcm = np.asarray(np.round(scaled * 32767.0), dtype="<i2")
    with wave.open(str(path), "wb") as stream:
        stream.setnchannels(1)
        stream.setsampwidth(2)
        stream.setframerate(sample_rate_hz)
        stream.writeframes(pcm.tobytes())


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


