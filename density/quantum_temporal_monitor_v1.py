class QuantumRhythmProjector:
    """Preserve event timing up to one declared uniform dilation."""

    def __init__(self, time_scale: float = 1.0, amplitude: float = 1.0):
        self.time_scale = _finite(time_scale, "time_scale", minimum=0.0)
        self.amplitude = _finite(amplitude, "amplitude", minimum=0.0)
        if self.time_scale <= 0.0:
            raise ValueError("time_scale must be positive")

    def project(self, event: QuantumEvent) -> ResonatorExcitation:
        if not isinstance(event, QuantumEvent):
            raise TypeError("project requires a QuantumEvent")
        return ResonatorExcitation(
            onset_s=self.time_scale * event.time_s,
            amplitude=self.amplitude,
            source=event.channel,
            event_id=event.event_id,
            source_time_s=event.time_s,
            time_scale=self.time_scale,
        )

    def process(self, event: QuantumEvent | None) -> tuple[ResonatorExcitation, ...]:
        return () if event is None else (self.project(event),)


ObservableFunction: TypeAlias = Callable[[ComplexMatrix], Mapping[str, float]]


def qubit_observables(rho: ComplexMatrix) -> Mapping[str, float]:
    state = _density(rho)
    if state.shape != (2, 2):
        raise ValueError("qubit_observables requires a 2x2 density matrix")
    return {
        "population_ground": float(state[0, 0].real),
        "population_excited": float(state[1, 1].real),
        "pauli_x": float(np.trace(state @ SIGMA_X).real),
        "pauli_y": float(np.trace(state @ SIGMA_Y).real),
        "pauli_z": float(np.trace(state @ SIGMA_Z).real),
        "purity": float(np.trace(state @ state).real),
    }


@dataclass(frozen=True)
class QMWTemporalFrame:
    """One synchronized frame after conditional measurement backaction."""

    time_s: float
    revision: int
    rho: ComplexMatrix
    quantum_event: QuantumEvent | None
    observables: Mapping[str, float]
    excitations: tuple[ResonatorExcitation, ...]
    source_id: str
    causal_order: tuple[str, ...] = (
        "quantum_measurement_and_backaction",
        "observables",
        "rhythm_projection",
        "sound",
    )
    provenance: str = "qmw_temporal_frame_simulated_monitor_v1"

    def __post_init__(self) -> None:
        object.__setattr__(self, "time_s", _finite(self.time_s, "time_s", minimum=0.0))
        if isinstance(self.revision, bool) or int(self.revision) != self.revision or self.revision < 0:
            raise ValueError("revision must be a nonnegative integer")
        object.__setattr__(self, "revision", int(self.revision))
        object.__setattr__(self, "rho", _density(self.rho))
        if self.quantum_event is not None and not isinstance(self.quantum_event, QuantumEvent):
            raise TypeError("quantum_event must be QuantumEvent or None")
        values = {str(key): _finite(value, f"observable {key}") for key, value in self.observables.items()}
        object.__setattr__(self, "observables", MappingProxyType(values))
        excitations = tuple(self.excitations)
        if any(not isinstance(value, ResonatorExcitation) for value in excitations):
            raise TypeError("excitations must contain ResonatorExcitation values")
        object.__setattr__(self, "excitations", excitations)
        object.__setattr__(self, "source_id", _label(self.source_id, "source_id"))
        expected = (
            "quantum_measurement_and_backaction",
            "observables",
            "rhythm_projection",
            "sound",
        )
        if tuple(self.causal_order) != expected:
            raise ValueError("QMWTemporalFrame causal order is fixed in v1")


def advance_monitored_frame(
    *,
    engine: QuantumTrajectoryEngine,
    rho: ComplexMatrix,
    hamiltonian: ComplexMatrix,
    monitor: MonitorOp,
    time_s: float,
    dt_s: float,
    revision: int,
    projector: QuantumRhythmProjector,
    observable_function: ObservableFunction = qubit_observables,
) -> QMWTemporalFrame:
    """Advance one monitor tick in the required causal order."""

    if time_s < monitor.start_s or time_s + dt_s > monitor.stop_s + 1e-12:
        raise ValueError("monitor tick must lie entirely inside the MonitorOp span")
    state_after, event = engine.step(
        rho=rho,
        hamiltonian=hamiltonian,
        channels=monitor.channels,
        time_s=time_s,
        dt_s=dt_s,
        source_id=monitor.event_id,
    )
    observables = observable_function(state_after)
    excitations = projector.process(event)
    return QMWTemporalFrame(
        time_s=time_s + dt_s,
        revision=revision,
        rho=state_after,
        quantum_event=event,
        observables=observables,
        excitations=excitations,
        source_id=monitor.event_id,
    )


def inter_event_intervals(events: Sequence[QuantumEvent]) -> RealVector:
    times = np.asarray([event.time_s for event in events], dtype=float)
    if times.size > 1 and np.any(np.diff(times) < 0.0):
        raise ValueError("events must be ordered by time")
    return np.diff(times)


def counts_per_window(
    events: Sequence[QuantumEvent], *, window_s: float, duration_s: float, start_s: float = 0.0
) -> NDArray[np.int64]:
    window = _finite(window_s, "window_s", minimum=0.0)
    duration = _finite(duration_s, "duration_s", minimum=0.0)
    start = _finite(start_s, "start_s", minimum=0.0)
    if window <= 0.0 or duration <= 0.0:
        raise ValueError("window_s and duration_s must be positive")
    number = duration / window
    rounded = int(round(number))
    if rounded < 1 or not math.isclose(number, rounded, rel_tol=0.0, abs_tol=1e-10):
        raise ValueError("duration_s must contain an integer number of equal counting windows")
    times = np.asarray([event.time_s for event in events], dtype=float)
    if times.size and (float(times.min()) < start - 1e-12 or float(times.max()) > start + duration + 1e-12):
        raise ValueError("event lies outside the declared counting span")
    edges = start + np.arange(rounded + 1, dtype=float) * window
    counts, _ = np.histogram(times, bins=edges)
    return counts.astype(np.int64, copy=False)


def factorial_cumulants(counts: NDArray[np.integer], maximum_order: int) -> RealVector:
    values = np.asarray(counts)
    if values.ndim != 1 or values.size < 1:
        raise ValueError("counts must be a nonempty one-dimensional array")
    if not np.issubdtype(values.dtype, np.integer) or np.any(values < 0):
        raise ValueError("counts must contain nonnegative integers")
    if isinstance(maximum_order, bool) or int(maximum_order) != maximum_order or maximum_order < 1:
        raise ValueError("maximum_order must be a positive integer")
    order_limit = int(maximum_order)
    factorial_moments = np.zeros(order_limit + 1, dtype=float)
    cumulants = np.zeros(order_limit + 1, dtype=float)
    factorial_moments[0] = 1.0
    float_counts = values.astype(float)
    for order in range(1, order_limit + 1):
        falling = np.ones_like(float_counts)
        for k in range(order):
            falling *= float_counts - k
        factorial_moments[order] = float(falling.mean())
    for order in range(1, order_limit + 1):
        value = factorial_moments[order]
        for k in range(1, order):
            value -= comb(order - 1, k - 1) * cumulants[k] * factorial_moments[order - k]
        cumulants[order] = value
    return cumulants[1:]


@dataclass(frozen=True)
class DetectorModel:
    """Declared independent missed-event and false-positive model.

    ``efficiency`` is independent Bernoulli thinning of true events. False
    events are an independent Poisson process. Under those assumptions the
    first factorial cumulant loses the false-event mean and higher orders scale
    by efficiency**order. This is a correction model, not detector evidence.
    """

    efficiency: float = 1.0
    false_event_rate_hz: float = 0.0

    def __post_init__(self) -> None:
        efficiency = _finite(self.efficiency, "detector efficiency", minimum=0.0)
        false_rate = _finite(self.false_event_rate_hz, "false event rate", minimum=0.0)
        if efficiency <= 0.0 or efficiency > 1.0:
            raise ValueError("detector efficiency must lie in (0, 1]")
        object.__setattr__(self, "efficiency", efficiency)
        object.__setattr__(self, "false_event_rate_hz", false_rate)


def detector_corrected_factorial_cumulants(
    observed: Sequence[float], *, window_s: float, model: DetectorModel
) -> RealVector:
    """Invert the declared thinning-plus-Poisson-background cumulant model."""

    if not isinstance(model, DetectorModel):
        raise TypeError("model must be a DetectorModel")
    window = _finite(window_s, "window_s", minimum=0.0)
    if window <= 0.0:
        raise ValueError("window_s must be positive")
    values = np.asarray(observed, dtype=float)
    if values.ndim != 1 or values.size < 1 or not np.all(np.isfinite(values)):
        raise ValueError("observed cumulants must be a finite nonempty vector")
    corrected = np.empty_like(values)
    corrected[0] = (values[0] - model.false_event_rate_hz * window) / model.efficiency
    for index in range(1, len(values)):
        corrected[index] = values[index] / model.efficiency ** (index + 1)
    return _immutable_array(corrected, np.float64)


def bootstrap_factorial_cumulants(
    counts: NDArray[np.integer],
    maximum_order: int,
    *,
    resamples: int = 2000,
    seed: int = 271828,
) -> NDArray[np.float64]:
    """Return deterministic percentile 95% intervals from counting windows."""

    values = np.asarray(counts)
    # Reuse the strict value/order validation before allocating the bootstrap.
    factorial_cumulants(values, maximum_order)
    if isinstance(resamples, bool) or int(resamples) != resamples or resamples < 100:
        raise ValueError("resamples must be an integer of at least 100")
    rng = np.random.default_rng(int(seed))
    estimates = np.empty((int(resamples), int(maximum_order)), dtype=float)
    for index in range(int(resamples)):
        sample = rng.choice(values, size=values.size, replace=True)
        estimates[index] = factorial_cumulants(sample, maximum_order)
    intervals = np.percentile(estimates, (2.5, 97.5), axis=0).T
    return _immutable_array(intervals, np.float64)


def poisson_count_diagnostics(counts: NDArray[np.integer]) -> Mapping[str, object]:
    """Compare window counts with a fitted Poisson reference without overclaiming."""

    values = np.asarray(counts)
    factorial_cumulants(values, 1)
    mean = float(values.mean())
    variance = float(values.var(ddof=1)) if values.size > 1 else 0.0
    fano = None if mean == 0.0 else variance / mean
    observed_maximum = int(values.max(initial=0))
    support_maximum = max(observed_maximum, int(math.ceil(mean + 8.0 * math.sqrt(mean) + 10.0)))
    support = np.arange(support_maximum + 1, dtype=int)
    poisson = np.empty(support_maximum + 1, dtype=float)
    poisson[0] = math.exp(-mean)
    for index in range(1, len(poisson)):
        poisson[index] = poisson[index - 1] * mean / index
    observed = np.bincount(values, minlength=len(poisson)).astype(float) / values.size
    tail = max(0.0, 1.0 - float(poisson.sum()))
    total_variation = 0.5 * (float(np.sum(np.abs(observed - poisson))) + tail)
    if values.size < 30:
        inference = "descriptive_only_fewer_than_30_windows"
    elif fano is not None and abs(fano - 1.0) <= 0.2:
        inference = "approximately_poisson_by_dispersion_only"
    else:
        inference = "dispersion_departs_from_poisson_reference"
    return MappingProxyType(
        {
            "window_count": int(values.size),
            "mean_count": mean,
            "sample_variance": variance,
            "fano_factor": fano,
            "poisson_total_variation_distance": total_variation,
            "poisson_fit_parameter": "empirical_mean_count",
            "inference": inference,
            "claim_boundary": "irregularity or dispersion alone does not establish nonclassical timing",
        }
    )


@dataclass(frozen=True)
class FullCountingStatistics:
    window_s: float
    duration_s: float
    counts: NDArray[np.int64]
    count_values: NDArray[np.int64]
    probabilities: RealVector
    factorial_cumulants: RealVector
    factorial_cumulant_ci95: NDArray[np.float64]
    poisson_diagnostics: Mapping[str, object]
    detector_model: DetectorModel
    detector_corrected_factorial_cumulants: RealVector
    bootstrap_seed: int
    bootstrap_resamples: int
    provenance: str = "simulated_event_stream_nonoverlapping_windows_v1"

    def __post_init__(self) -> None:
        window = _finite(self.window_s, "window_s", minimum=0.0)
        duration = _finite(self.duration_s, "duration_s", minimum=0.0)
        if window <= 0.0 or duration <= 0.0:
            raise ValueError("counting window and duration must be positive")
        counts = np.asarray(self.counts, dtype=np.int64)
        count_values = np.asarray(self.count_values, dtype=np.int64)
        probabilities = np.asarray(self.probabilities, dtype=float)
        cumulants = np.asarray(self.factorial_cumulants, dtype=float)
        intervals = np.asarray(self.factorial_cumulant_ci95, dtype=float)
        corrected = np.asarray(self.detector_corrected_factorial_cumulants, dtype=float)
        if counts.ndim != 1 or counts.size < 1 or np.any(counts < 0):
            raise ValueError("counts must be a nonempty nonnegative vector")
        if count_values.ndim != 1 or probabilities.shape != count_values.shape:
            raise ValueError("count values and probabilities must be matching vectors")
        if cumulants.ndim != 1 or cumulants.size < 1:
            raise ValueError("factorial cumulants must be a nonempty vector")
        if intervals.shape != (cumulants.size, 2) or not np.all(np.isfinite(intervals)):
            raise ValueError("factorial cumulant intervals must have shape (orders, 2)")
        if corrected.shape != cumulants.shape or not np.all(np.isfinite(corrected)):
            raise ValueError("detector-corrected cumulants must match observed orders")
        if not isinstance(self.poisson_diagnostics, Mapping) or not isinstance(self.detector_model, DetectorModel):
            raise TypeError("counting diagnostics and DetectorModel are required")
        if isinstance(self.bootstrap_seed, bool) or int(self.bootstrap_seed) != self.bootstrap_seed:
            raise ValueError("bootstrap_seed must be an integer")
        if isinstance(self.bootstrap_resamples, bool) or int(self.bootstrap_resamples) != self.bootstrap_resamples or self.bootstrap_resamples < 100:
            raise ValueError("bootstrap_resamples must be an integer of at least 100")
        if np.any(probabilities < 0.0) or not math.isclose(
            float(probabilities.sum()), 1.0, rel_tol=0.0, abs_tol=1e-12
        ):
            raise ValueError("count probabilities must form a normalized distribution")
        counts = _immutable_array(counts, np.int64)
        count_values = _immutable_array(count_values, np.int64)
        probabilities = _immutable_array(probabilities, np.float64)
        cumulants = _immutable_array(cumulants, np.float64)
        intervals = _immutable_array(intervals, np.float64)
        corrected = _immutable_array(corrected, np.float64)
        object.__setattr__(self, "window_s", window)
        object.__setattr__(self, "duration_s", duration)
        object.__setattr__(self, "counts", counts)
        object.__setattr__(self, "count_values", count_values)
        object.__setattr__(self, "probabilities", probabilities)
        object.__setattr__(self, "factorial_cumulants", cumulants)
        object.__setattr__(self, "factorial_cumulant_ci95", intervals)
        object.__setattr__(self, "poisson_diagnostics", MappingProxyType(dict(self.poisson_diagnostics)))
        object.__setattr__(self, "detector_corrected_factorial_cumulants", corrected)
        object.__setattr__(self, "bootstrap_seed", int(self.bootstrap_seed))
        object.__setattr__(self, "bootstrap_resamples", int(self.bootstrap_resamples))
        object.__setattr__(self, "provenance", _label(self.provenance, "provenance"))

    def to_record(self) -> dict[str, object]:
        return {
            "window_s": self.window_s,
            "duration_s": self.duration_s,
            "counts": self.counts.tolist(),
            "P_N": {
                str(int(count)): float(probability)
                for count, probability in zip(self.count_values, self.probabilities)
            },
            "factorial_cumulants": self.factorial_cumulants.tolist(),
            "factorial_cumulant_ci95": self.factorial_cumulant_ci95.tolist(),
            "poisson_diagnostics": dict(self.poisson_diagnostics),
            "detector_model": asdict(self.detector_model),
            "detector_corrected_factorial_cumulants": self.detector_corrected_factorial_cumulants.tolist(),
            "detector_correction_assumptions": "independent Bernoulli thinning plus independent Poisson false events",
            "bootstrap": {"seed": self.bootstrap_seed, "resamples": self.bootstrap_resamples, "interval": "percentile_95"},
            "orders": list(range(1, len(self.factorial_cumulants) + 1)),
            "provenance": self.provenance,
        }


def full_counting_statistics(
    events: Sequence[QuantumEvent],
    *,
    window_s: float,
    duration_s: float,
    maximum_order: int = 4,
    start_s: float = 0.0,
    detector_model: DetectorModel = DetectorModel(),
    bootstrap_seed: int = 271828,
    bootstrap_resamples: int = 2000,
) -> FullCountingStatistics:
    counts = counts_per_window(events, window_s=window_s, duration_s=duration_s, start_s=start_s)
    values = np.arange(int(counts.max(initial=0)) + 1, dtype=np.int64)
    probabilities = np.bincount(counts, minlength=len(values)).astype(float) / counts.size
    cumulants = factorial_cumulants(counts, maximum_order)
    return FullCountingStatistics(
        window_s=float(window_s),
        duration_s=float(duration_s),
        counts=counts,
        count_values=values,
        probabilities=probabilities,
        factorial_cumulants=cumulants,
        factorial_cumulant_ci95=bootstrap_factorial_cumulants(
            counts, maximum_order, resamples=bootstrap_resamples, seed=bootstrap_seed
        ),
        poisson_diagnostics=poisson_count_diagnostics(counts),
        detector_model=detector_model,
        detector_corrected_factorial_cumulants=detector_corrected_factorial_cumulants(
            cumulants, window_s=window_s, model=detector_model
        ),
        bootstrap_seed=bootstrap_seed,
        bootstrap_resamples=bootstrap_resamples,
    )


@dataclass(frozen=True)
class DrivenQubitExperimentConfig:
    duration_s: float = 10.0
    dt_s: float = 0.0005
    rabi_hz: float = 3.0
    decay_rate_hz: float = 4.0
    seed: int = 42
    counting_window_s: float = 0.5
    monitor_id: str = "monitor-001"

    def __post_init__(self) -> None:
        duration = _finite(self.duration_s, "duration_s", minimum=0.0)
        dt = _finite(self.dt_s, "dt_s", minimum=0.0)
        rabi = _finite(self.rabi_hz, "rabi_hz", minimum=0.0)
        decay = _finite(self.decay_rate_hz, "decay_rate_hz", minimum=0.0)
        window = _finite(self.counting_window_s, "counting_window_s", minimum=0.0)
        if min(duration, dt, rabi, decay, window) <= 0.0:
            raise ValueError("experiment rates, durations, dt, and counting window must be positive")
        steps = duration / dt
        if not math.isclose(steps, round(steps), rel_tol=0.0, abs_tol=1e-9):
            raise ValueError("duration_s must contain an integer number of dt_s steps")
        windows = duration / window
        if not math.isclose(windows, round(windows), rel_tol=0.0, abs_tol=1e-9):
            raise ValueError("duration_s must contain an integer number of counting windows")
        object.__setattr__(self, "duration_s", duration)
        object.__setattr__(self, "dt_s", dt)
        object.__setattr__(self, "rabi_hz", rabi)
        object.__setattr__(self, "decay_rate_hz", decay)
        object.__setattr__(self, "counting_window_s", window)
        object.__setattr__(self, "seed", int(self.seed))
        object.__setattr__(self, "monitor_id", _label(self.monitor_id, "monitor_id"))


@dataclass(frozen=True)
class DrivenQubitExperimentResult:
    config: DrivenQubitExperimentConfig
    graph: QuantumPerformanceGraph
    events: tuple[QuantumEvent, ...]
    event_frames: tuple[QMWTemporalFrame, ...]
    final_rho: ComplexMatrix
    statistics: FullCountingStatistics

    def __post_init__(self) -> None:
        if not isinstance(self.config, DrivenQubitExperimentConfig):
            raise TypeError("config must be DrivenQubitExperimentConfig")
        if not isinstance(self.graph, QuantumPerformanceGraph):
            raise TypeError("graph must be QuantumPerformanceGraph")
        events = tuple(self.events)
        frames = tuple(self.event_frames)
        if any(not isinstance(value, QuantumEvent) for value in events):
            raise TypeError("events must contain QuantumEvent values")
        if any(not isinstance(value, QMWTemporalFrame) for value in frames):
            raise TypeError("event_frames must contain QMWTemporalFrame values")
        if len(events) != len(frames):
            raise ValueError("each event must have one synchronized event frame")
        if any(frame.quantum_event is not event for frame, event in zip(frames, events)):
            raise ValueError("event frames must retain the exact event identities")
        object.__setattr__(self, "events", events)
        object.__setattr__(self, "event_frames", frames)
        object.__setattr__(self, "final_rho", _density(self.final_rho, "final_rho"))
        if not isinstance(self.statistics, FullCountingStatistics):
            raise TypeError("statistics must be FullCountingStatistics")

    @property
    def dwell_times_s(self) -> RealVector:
        return inter_event_intervals(self.events)


def driven_qubit_model(config: DrivenQubitExperimentConfig) -> tuple[ComplexMatrix, MonitorOp, ComplexMatrix]:
    omega = 2.0 * math.pi * config.rabi_hz
    hamiltonian = 0.5 * omega * SIGMA_X
    channel = JumpChannel("decay", math.sqrt(config.decay_rate_hz) * SIGMA_MINUS)
    monitor = MonitorOp(config.monitor_id, 0.0, config.duration_s, (channel,))
    rho_initial = np.array([[1.0, 0.0], [0.0, 0.0]], dtype=np.complex128)
    return hamiltonian, monitor, rho_initial


def run_driven_qubit_experiment(
    config: DrivenQubitExperimentConfig = DrivenQubitExperimentConfig(),
) -> DrivenQubitExperimentResult:
    hamiltonian, monitor, rho = driven_qubit_model(config)
    graph = QuantumPerformanceGraph((monitor,))
    engine = QuantumTrajectoryEngine(seed=config.seed)
    projector = QuantumRhythmProjector(time_scale=1.0, amplitude=1.0)
    events: list[QuantumEvent] = []
    event_frames: list[QMWTemporalFrame] = []
    number_of_steps = int(round(config.duration_s / config.dt_s))
    for step_index in range(number_of_steps):
        frame = advance_monitored_frame(
            engine=engine,
            rho=rho,
            hamiltonian=hamiltonian,
            monitor=monitor,
            time_s=step_index * config.dt_s,
            dt_s=config.dt_s,
            revision=step_index + 1,
            projector=projector,
        )
        rho = frame.rho
        if frame.quantum_event is not None:
            events.append(frame.quantum_event)
            event_frames.append(frame)
    statistics = full_counting_statistics(
        events,
        window_s=config.counting_window_s,
        duration_s=config.duration_s,
        maximum_order=4,
    )
    return DrivenQubitExperimentResult(
        config=config,
        graph=graph,
        events=tuple(events),
        event_frames=tuple(event_frames),
        final_rho=rho,
        statistics=statistics,
    )


@dataclass(frozen=True)
class FixedResonator:
    frequency_hz: float = 440.0
    decay_s: float = 0.35
    sample_rate_hz: int = 12_000
    tail_decay_constants: float = 7.0

    def __post_init__(self) -> None:
        frequency = _finite(self.frequency_hz, "frequency_hz", minimum=0.0)
        decay = _finite(self.decay_s, "decay_s", minimum=0.0)
        tail = _finite(self.tail_decay_constants, "tail_decay_constants", minimum=0.0)
        if min(frequency, decay, tail) <= 0.0:
            raise ValueError("resonator frequency, decay, and tail must be positive")
        if isinstance(self.sample_rate_hz, bool) or int(self.sample_rate_hz) != self.sample_rate_hz:
            raise ValueError("sample_rate_hz must be an integer")
        sample_rate = int(self.sample_rate_hz)
        if sample_rate < 2 * frequency:
            raise ValueError("sample rate must exceed the Nyquist rate")
        object.__setattr__(self, "frequency_hz", frequency)
        object.__setattr__(self, "decay_s", decay)
        object.__setattr__(self, "tail_decay_constants", tail)
        object.__setattr__(self, "sample_rate_hz", sample_rate)

    def render(self, excitations: Sequence[ResonatorExcitation]) -> NDArray[np.float32]:
        declared = tuple(excitations)
        if any(not isinstance(value, ResonatorExcitation) for value in declared):
            raise TypeError("resonator input must contain ResonatorExcitation values")
        tail_s = self.tail_decay_constants * self.decay_s
        last_onset = max((event.onset_s for event in declared), default=0.0)
        sample_count = max(1, int(math.ceil((last_onset + tail_s) * self.sample_rate_hz)) + 1)
        output = np.zeros(sample_count, dtype=np.float32)
        response_count = int(math.ceil(tail_s * self.sample_rate_hz)) + 1
        time = np.arange(response_count, dtype=float) / self.sample_rate_hz
        response = np.exp(-time / self.decay_s) * np.sin(2.0 * math.pi * self.frequency_hz * time)
        for excitation in declared:
            start = int(round(excitation.onset_s * self.sample_rate_hz))
            stop = min(sample_count, start + response_count)
            output[start:stop] += np.asarray(
                excitation.amplitude * response[: stop - start], dtype=np.float32
            )
        return output


def _complex_record(matrix: ComplexMatrix) -> dict[str, object]:
    return {"real": np.asarray(matrix).real.tolist(), "imag": np.asarray(matrix).imag.tolist()}


def _operation_record(operation: ProcessOp) -> dict[str, object]:
    if isinstance(operation, GateOp):
        return {
            "kind": "gate",
            "event_id": operation.event_id,
            "time_s": operation.time_s,
            "targets": list(operation.targets),
            "unitary": _complex_record(operation.unitary),
        }
    if isinstance(operation, MeasureOp):
        return {
            "kind": "measure",
            "event_id": operation.event_id,
            "time_s": operation.time_s,
            "targets": list(operation.targets),
            "kraus_operators": [_complex_record(value) for value in operation.kraus_operators],
        }
    return {
        "kind": "monitor",
        "event_id": operation.event_id,
        "start_s": operation.start_s,
        "stop_s": operation.stop_s,
        "channels": [
            {"name": channel.name, "operator": _complex_record(channel.operator)}
            for channel in operation.channels
        ],
    }


