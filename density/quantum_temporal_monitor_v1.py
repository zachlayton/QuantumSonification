    output = Path(output_directory).expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)
    scales = tuple(_finite(value, "time scale", minimum=0.0) for value in time_scales)
    if not scales or any(value <= 0.0 for value in scales) or len(set(scales)) != len(scales):
        raise ValueError("time_scales must contain unique positive values")

    events_path = output / "quantum_events.csv"
    with events_path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(
            stream,
            fieldnames=(
                "event_id", "time_s", "interval_from_previous_s", "source_id", "channel",
                "rate_hz", "step_probability", "backaction_norm", "origin",
            ),
        )
        writer.writeheader()
        previous: float | None = None
        for event in result.events:
            writer.writerow(
                {
                    "event_id": event.event_id,
                    "time_s": f"{event.time_s:.12g}",
                    "interval_from_previous_s": "" if previous is None else f"{event.time_s - previous:.12g}",
                    "source_id": event.source_id,
                    "channel": event.channel,
                    "rate_hz": f"{event.rate_hz:.12g}",
                    "step_probability": f"{event.probability:.12g}",
                    "backaction_norm": f"{event.backaction_norm:.12g}",
                    "origin": event.origin,
                }
            )
            previous = event.time_s

    dwell_path = output / "dwell_times.csv"
    with dwell_path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(("interval_index", "start_event_id", "stop_event_id", "dwell_time_s"))
        for index, (first, second) in enumerate(zip(result.events, result.events[1:]), start=1):
            writer.writerow((index, first.event_id, second.event_id, f"{second.time_s - first.time_s:.12g}"))

    statistics_path = output / "full_counting_statistics.json"
    statistics_path.write_text(
        json.dumps(result.statistics.to_record(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    timeline_path = output / "circuit_zx_temporal_timeline.svg"
    timeline_path.write_text(render_temporal_svg(result.graph, result.events), encoding="utf-8")

    schedules: dict[str, list[ResonatorExcitation]] = {}
    generated_paths: list[Path] = [events_path, dwell_path, statistics_path, timeline_path]
    for scale in scales:
        key = f"{scale:g}x"
        projected = [QuantumRhythmProjector(scale, 1.0).project(event) for event in result.events]
        schedules[key] = projected
        schedule_path = output / f"resonator_excitations_{key}.csv"
        with schedule_path.open("w", newline="", encoding="utf-8") as stream:
            writer = csv.DictWriter(
                stream,
                fieldnames=("event_id", "source_time_s", "onset_s", "time_scale", "amplitude", "source"),
            )
            writer.writeheader()
            for excitation in projected:
                writer.writerow(asdict(excitation))
        generated_paths.append(schedule_path)

    if render_audio:
        rendered = {key: resonator.render(values) for key, values in schedules.items()}
        global_peak = max((float(np.max(np.abs(value), initial=0.0)) for value in rendered.values()), default=0.0)
        gain = 0.9 / global_peak if global_peak > 0.0 else 1.0
        for key, samples in rendered.items():
            audio_path = output / f"fixed_resonator_{key}.wav"
            _write_pcm16(audio_path, samples, resonator.sample_rate_hz, gain)
            generated_paths.append(audio_path)
    else:
        gain = None

    manifest = {
        "schema": "qmw_quantum_temporal_monitor_experiment_001_v1",
        "scientific_scope": {
            "process": "simulated driven one-qubit conditional quantum-jump trajectory",
            "rhythm_origin": "emergent simulated jump timestamps",
            "not_claimed": [
                "hardware observation",
                "detector reconstruction",
                "uniquely nonclassical timing inferred from irregularity alone",
                "temporal quantum tomography implementation",
                "resolution of the measurement problem",
            ],
            "causal_order": list(QMWTemporalFrame.causal_order),
        },
        "references": {
            "counting_statistics_and_detector_errors": APS_COUNTING_REFERENCE,
            "history_dependent_temporal_tomography_boundary": TEMPORAL_TOMOGRAPHY_REFERENCE,
            "unitary_correlation_vs_selective_outcome_boundary": WIGNER_MEASUREMENT_REFERENCE,
        },
        "config": asdict(result.config),
        "performance_graph": {
            "compiler_provenance": result.graph.compiler_provenance,
            "operations": [_operation_record(value) for value in result.graph.operations],
        },
        "event_count": len(result.events),
        "events": [event.to_record(include_matrices=True) for event in result.events],
        "final_rho": _complex_record(result.final_rho),
        "counting_statistics": result.statistics.to_record(),
        "time_scales": list(scales),
        "projection": {
            "amplitude": 1.0,
            "quantization": None,
            "meter": None,
            "resonator_frequency_hz": resonator.frequency_hz,
            "resonator_decay_s": resonator.decay_s,
            "sample_rate_hz": resonator.sample_rate_hz,
            "shared_audio_gain": gain,
        },
        "files": {
            path.name: {"sha256": _sha256(path), "bytes": path.stat().st_size}
            for path in generated_paths
        },
    }
    manifest_path = output / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest_path


